import { writeFile } from 'node:fs/promises';
import { fixtureRoot, cacheRoot, readJson, hash, root, sourceHash } from './common.mjs';
import { shiftedSymbolBounds } from './major-calibration-metrics.mjs';

// Emit only profiles that survived independent production raster verification.
// Deltas are relative to the captured baseline, including the earlier six
// frame-plate pilot profiles. Those remain in styled-symbol-placement.ts.
const report = await readJson(`${fixtureRoot}/major-set-calibration.json`);
if (!report.complete) throw Error('Complete the measurement and raster validation batch first');
const manifest = await readJson(`${root}/games/magic/assets.json`);
const rendererHash = await sourceHash(`${root}/games/magic/src`);
for (const row of report.rows.filter((r) => r.status === 'validated-symbol-profile')) {
  if (row.rendererHash !== rendererHash) throw Error('Renderer changed since calibration');
  const capture = await readJson(
    `${cacheRoot}/rollout/major-calibration/${row.key.replaceAll('/', '-')}.json`,
  );
  if (hash(JSON.stringify(capture)) !== row.captureHash) throw Error('Capture identity changed');
  const roi = row.family === 'retro' ? [350, 370, 462, 416] : [377, 379, 463, 424];
  for (const sample of capture.samples.filter((s) => s.bounds)) {
    const [x, y, w, h] = shiftedSymbolBounds(sample.bounds, row.symbol.params);
    if (x < roi[0] || y < roi[1] || x + w > roi[2] || y + h > roi[3])
      throw Error(`Symbol escaped measurement region: ${row.key} / ${sample.name}`);
  }
}
const profiles = Object.fromEntries(
  report.rows
    .filter((r) => r.status === 'validated-symbol-profile')
    .map((r) => [r.key, r.symbol.params.map((n) => Math.round(n * 1000000) / 1000000)]),
);
if (!Object.keys(profiles).length) throw Error('No validated profiles');
const source = `// Generated by major-calibration-adopt.mjs. Canonical 488 × 680 coordinates.
// Report SHA-256: ${hash(JSON.stringify(report))}
// [right-edge dx, center dy, width scale, height scale]. Frame-only scan poses
// and reserved names are recorded in fixtures/accuracy/major-set-calibration.json.
export const MAJOR_SYMBOL_SOURCE = ${JSON.stringify(manifest.CONJURER_ROOT)};
export const MAJOR_SYMBOL_PROFILES: Readonly<Record<string, readonly [number, number, number, number]>> = ${JSON.stringify(profiles, null, 2)};
`;
await writeFile(`${root}/games/magic/src/presentation/major-symbol-profiles.ts`, source);
const frames = Object.fromEntries(
  report.rows
    .filter((r) => r.frameCalibration?.status === 'validated')
    .map((r) => [`${r.set}/${r.border}`, r.frameCalibration.inset]),
);
await writeFile(
  `${root}/games/magic/src/presentation/major-frame-profiles.ts`,
  `// Generated by major-calibration-adopt.mjs; ordinary component frames only.\n// Report SHA-256: ${hash(JSON.stringify(report))}\nexport const MAJOR_FRAME_SOURCE = ${JSON.stringify(manifest.RENDERER_COMPONENT_ROOT)};\nexport const MAJOR_FRAME_INSETS: Readonly<Record<string, number>> = ${JSON.stringify(frames, null, 2)};\n`,
);
console.log('Generated', Object.keys(profiles).length, 'validated set/frame/stock profiles');
console.log('Generated', Object.keys(frames).length, 'validated component frame insets');
