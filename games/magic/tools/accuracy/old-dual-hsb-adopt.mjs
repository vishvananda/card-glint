import assert from 'node:assert/strict';
import { readJson, writeJson, fixtureRoot, root, hash, atomicWrite } from './common.mjs';
const result = await readJson(fixtureRoot + '/old-dual-hsb-results.json'),
  candidate = await readJson(fixtureRoot + '/old-dual-hsb-candidate.json');
assert.equal(result.candidateHash, hash(JSON.stringify(candidate)));
assert.deepEqual(result.provenance, candidate.provenance);
const printingScope = await readJson(fixtureRoot + '/hsb-printing-scope.json');
const frames = {},
  mana = {};
for (const g of result.groups.filter((g) => g.status === 'trial')) {
  const c = candidate.groups.find((c) => c.key === g.key);
  assert.equal(c.status, 'trial');
  assert.deepEqual(g.adjustment, c.adjustment);
  assert.deepEqual(g.source, c.source);
  const material = g.source.asset.split('/').at(-1).replace('.png', '').toUpperCase(),
    key = `${g.set}-${g.border}-${material}`;
  if (printingScope.excludedFrameKeys.includes(key)) continue;
  const profile = { asset: g.source.asset, rect: g.source.rect, adjustment: g.adjustment };
  if (frames[key]) assert.deepEqual(frames[key], profile, 'Ambiguous runtime profile');
  frames[key] = profile;
}
// Preserve the six source/stock-specific Revised profiles explicitly approved
// in visual review. New automatic gates annotate them; they do not silently
// undo that review or refit the already reviewed appearance.
const reviewed = await readJson(fixtureRoot + '/revised-dual-hsb.json');
assert.equal(reviewed.complete, true);
for (const g of reviewed.groups) {
  assert.equal(g.accepted, true);
  frames[`3ed-white-${g.material}`] = { asset: g.asset, rect: g.rect, adjustment: g.adjustment };
}
for (const g of result.mana.filter((g) => g.status === 'trial')) {
  const c = candidate.mana.find((c) => c.key === g.key);
  assert.equal(c.status, 'trial');
  assert.deepEqual(g.targetRgb, c.targetRgb);
  const key = `${g.set}-${g.border}-${g.symbol}`;
  if (!printingScope.excludedManaKeys.includes(key)) mana[key] = g.targetRgb;
}
await atomicWrite(
  root + '/games/magic/src/presentation/old-dual-hsb-profiles.ts',
  `// Generated by old-dual-hsb-adopt.mjs. Opt-in; six reviewed Revised overrides; no joint-fit fallback.\n// Results SHA-256: ${hash(JSON.stringify(result))}\nimport type {DualFrameHsb} from './frame-hsb.js';\nimport type {FaceRect} from './face-layout.js';\nimport type {Rgb} from './hsb.js';\nexport const DUAL_HSB_PROFILES: Readonly<Record<string,{asset:string;rect:FaceRect;adjustment:DualFrameHsb}>> = ${JSON.stringify(frames, null, 2)};\nexport const DUAL_MANA_TARGETS: Readonly<Record<string,Rgb>> = ${JSON.stringify(mana, null, 2)};\n`,
);
await writeJson(fixtureRoot + '/old-dual-hsb-runtime.json', {
  schemaVersion: 1,
  resultsHash: hash(JSON.stringify(result)),
  printingScopeHash: hash(JSON.stringify(printingScope)),
  reviewedRevisedHash: hash(JSON.stringify(reviewed)),
  frames: Object.entries(frames).map(([key, profile]) => ({
    key,
    source: key.startsWith('3ed-white-') ? 'visually-reviewed-revised' : 'reserved-validated',
    asset: profile.asset,
  })),
  mana: Object.keys(mana),
});
const plan = await readJson(fixtureRoot + '/old-frame-family-plan.json'),
  sampledKeys = new Set(result.groups.map((g) => g.key));
const unmeasured = plan.sets
  .flatMap((s) =>
    s.groups.map((g) => ({
      key: s.set + '/' + g.key,
      set: s.set,
      material: g.material,
      printings: g.printings,
      reason: 'no-frozen-reference-samples',
    })),
  )
  .filter((g) => !sampledKeys.has(g.key));
await writeJson(fixtureRoot + '/old-dual-hsb-review.json', {
  schemaVersion: 1,
  resultsHash: hash(JSON.stringify(result)),
  summary: { ...result.summary, unmeasuredInventoryGroups: unmeasured.length },
  unmeasured,
  groups: result.groups
    .filter((g) => g.status !== 'trial')
    .map((g) => ({
      key: g.key,
      count: g.count,
      flags: g.flags,
      components: g.components,
      texture: g.texture,
    })),
  mana: result.mana
    .filter((g) => g.status !== 'trial')
    .map((g) => ({ key: g.key, count: g.count, flags: g.flags })),
});
console.log(
  'Adopted',
  Object.keys(frames).length,
  'dual frame profiles and',
  Object.keys(mana).length,
  'mana targets',
);

await writeJson(fixtureRoot + '/old-dual-hsb-assets-review.json', {
  schemaVersion: 1,
  resultsHash: hash(JSON.stringify(result)),
  scope:
    'Residuals in existing source assets after fitting; these are review leads, not proof of faulty artwork. Contrast also reflects scan processing and patch geometry.',
  assets: [
    ...new Set(
      result.groups
        .filter((g) => g.flags.some((f) => f.startsWith('texture-')))
        .map((g) => g.source?.asset)
        .filter(Boolean),
    ),
  ].map((asset) => ({
    asset,
    groups: result.groups
      .filter((g) => g.source?.asset === asset && g.flags.some((f) => f.startsWith('texture-')))
      .map((g) => ({
        key: g.key,
        flags: g.flags.filter((f) => f.startsWith('texture-')),
        metrics: g.texture,
        references: g.rows.map((r) => ({ id: r.id, name: r.name, referenceHash: r.referenceHash })),
      })),
  })),
});
