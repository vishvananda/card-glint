import assert from 'node:assert/strict';
import { fixtureRoot, root, readJson, hash, atomicWrite } from './common.mjs';
const report = await readJson(fixtureRoot + '/revised-dual-hsb.json');
assert.equal(report.complete, true, 'All six reserved cohorts must pass before adoption');
const profiles = Object.fromEntries(
  report.groups.map((g) => [
    g.material,
    { asset: g.asset, rect: g.rect, adjustment: g.adjustment },
  ]),
);
await atomicWrite(
  root + '/games/magic/src/presentation/revised-dual-hsb-profiles.ts',
  `// Generated by revised-dual-hsb-adopt.mjs; source/stock/placement guarded.\n// Results SHA-256: ${hash(JSON.stringify(report))}\nimport type { FaceRect } from './face-layout.js';\nimport type { DualFrameHsb } from './frame-hsb.js';\nexport const REVISED_DUAL_HSB_PROFILES: Readonly<Record<string,{asset:string;rect:FaceRect;adjustment:DualFrameHsb}>> = ${JSON.stringify(profiles, null, 2)};\n`,
);
