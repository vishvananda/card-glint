import { writeFile } from 'node:fs/promises';
import { readJson, cacheRoot, fixtureRoot, root, hash } from './common.mjs';
const proposal = await readJson(cacheRoot + '/rollout/mana-location.json'),
  verified = await readJson(fixtureRoot + '/mana-location-verified.json');
if (verified.proposalHash !== hash(JSON.stringify(proposal)))
  throw Error('Mana proposal changed after validation');
const profiles = Object.fromEntries(
  verified.groups
    .filter((g) => g.status === 'validated')
    .map((g) => {
      const p = proposal.groups.find((p) => p.key === g.key);
      if (p?.status !== 'candidate') throw Error('Missing candidate ' + g.key);
      return [g.key, [p.candidate.right, p.candidate.centerY, p.candidate.pitch, p.candidate.size]];
    }),
);
if (Object.values(profiles).some((p) => p.some((v) => !Number.isFinite(v))))
  throw Error('Invalid candidate coordinates');
await writeFile(
  root + '/games/magic/src/presentation/retro-mana-profiles.ts',
  `// Generated by mana-location-adopt.mjs; shared positions, no per-card offsets.\n// Production raster verification: ${hash(JSON.stringify(verified))}\nexport const RETRO_MANA_PROFILES: Readonly<Record<string, readonly [number, number, number, number]>> = ${JSON.stringify(profiles, null, 2)};\n`,
);
console.log(Object.keys(profiles).length, 'validated shared mana rows');
