import assert from 'node:assert/strict';
import { readJson, fixtureRoot, root, hash, atomicWrite } from './common.mjs';
const results = await readJson(`${fixtureRoot}/early-hsb-family-results.json`),
  candidate = await readJson(`${fixtureRoot}/early-hsb-family-candidate.json`),
  plan = await readJson(`${fixtureRoot}/early-hsb-plan.json`);
assert.equal(hash(JSON.stringify(candidate)), results.candidateHash);
assert.deepEqual(candidate.provenance, results.provenance);
assert.equal(
  results.provenance.familyHash,
  hash(JSON.stringify(await readJson(`${fixtureRoot}/old-frame-family-results.json`))),
);
function adopt(groups, frozen, include) {
  return Object.fromEntries(
    groups
      .filter(
        (g) =>
          g.status === 'trial' &&
          frozen.find((f) => f.key === g.key)?.status === 'trial' &&
          include(g),
      )
      .map((group) => {
        const source = frozen.find((g) => g.key === group.key);
        assert.ok(group.count >= 2 && source.count >= 3);
        assert.deepEqual(group.adjustment, source.adjustment);
        return [group.key, group.adjustment];
      }),
  );
}
// Land geometry and the striped dual overlay require a separate material study.
const profiles = adopt(results.groups, candidate.groups, (g) => /-(W|U|B|R|G|A)$/.test(g.key));
const frameAssets = Object.fromEntries(
  Object.keys(profiles).map((key) => [key, results.provenance.templates[key].asset]),
);
const frameRects = Object.fromEntries(
  Object.keys(profiles).map((key) => [key, results.provenance.templates[key].rect]),
);
const mana = adopt(results.mana, candidate.mana, () => true);
const manaTargets = Object.fromEntries(
  Object.keys(mana).map((key) => [key, candidate.mana.find((g) => g.key === key).targetRgb]),
);
await atomicWrite(
  `${root}/games/magic/src/presentation/early-hsb-profiles.ts`,
  `// Generated by hsb-adopt.mjs. Opt-in trial only.\n// Results SHA-256: ${hash(JSON.stringify(results))}\nimport type { HsbAdjustment, Rgb } from './hsb.js';\nimport type { FaceRect } from './face-layout.js';\nexport const EARLY_HSB_PROFILES: Readonly<Record<string, HsbAdjustment>> = ${JSON.stringify(profiles, null, 2)};\nexport const EARLY_HSB_FRAME_ASSETS: Readonly<Record<string, string>> = ${JSON.stringify(frameAssets, null, 2)};\nexport const EARLY_HSB_FRAME_RECTS: Readonly<Record<string,FaceRect>> = ${JSON.stringify(frameRects, null, 2)};\nexport const EARLY_MANA_HSB_PROFILES: Readonly<Record<string, HsbAdjustment>> = ${JSON.stringify(mana, null, 2)};\nexport const EARLY_MANA_TARGETS: Readonly<Record<string, Rgb>> = ${JSON.stringify(manaTargets, null, 2)};\n`,
);
console.log(
  'Generated',
  Object.keys(profiles).length,
  'whole-frame profiles;',
  Object.keys(mana).length,
  'mana profiles.',
);
