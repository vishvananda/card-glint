import assert from 'node:assert/strict';
import { readJson, fixtureRoot, root, hash, atomicWrite } from './common.mjs';
const results = await readJson(`${fixtureRoot}/early-hsb-results.json`),
  candidate = await readJson(`${fixtureRoot}/early-hsb-candidate.json`);
assert.equal(hash(JSON.stringify(candidate)), results.candidateHash);
const profiles = {};
for (const group of results.groups.filter((g) => g.status === 'trial')) {
  assert.ok(group.count >= 2);
  const source = candidate.groups.find(
    (g) => g.key === group.key && g.component === group.component,
  );
  assert.ok(source.count >= 3);
  assert.deepEqual(group.adjustment, source.adjustment);
  profiles[group.key] ??= {};
  profiles[group.key][group.component] = group.adjustment;
}
await atomicWrite(
  `${root}/games/magic/src/presentation/early-hsb-profiles.ts`,
  `// Generated by hsb-adopt.mjs. Opt-in trial only.\n// Results SHA-256: ${hash(JSON.stringify(results))}\nimport type { EarlyHsbProfile } from './early-hsb-material.js';\nexport const EARLY_HSB_PROFILES: Readonly<Record<string, EarlyHsbProfile>> = ${JSON.stringify(profiles, null, 2)};\n`,
);
console.log(
  'Generated',
  Object.keys(profiles).length,
  'set/material profiles;',
  results.groups.filter((g) => g.status === 'trial').length,
  'components.',
);
