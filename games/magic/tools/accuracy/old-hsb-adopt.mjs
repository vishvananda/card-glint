import assert from 'node:assert/strict';
import { readJson, writeJson, fixtureRoot, root, hash, atomicWrite } from './common.mjs';
const result = await readJson(`${fixtureRoot}/old-hsb-results.json`),
  candidate = await readJson(`${fixtureRoot}/old-hsb-candidate.json`),
  families = await readJson(`${fixtureRoot}/old-frame-family-results.json`);
assert.equal(result.candidateHash, hash(JSON.stringify(candidate)));
assert.deepEqual(result.provenance, candidate.provenance);
assert.equal(result.provenance.familyHash, hash(JSON.stringify(families)));
const sourceRoot = (await readJson(`${root}/games/magic/assets.json`)).RETRO_ROOT + '/img/frames/';
const frames = {},
  mana = {};
for (const g of result.groups.filter((g) => g.status === 'trial')) {
  const cal = candidate.groups.find((c) => c.key === g.key);
  assert.equal(cal.status, 'trial');
  assert.deepEqual(cal.adjustment, g.adjustment);
  assert.deepEqual(cal.source, g.source);
  assert.ok(g.source.asset.startsWith(sourceRoot));
  const material = g.source.asset.split('/').at(-1).replace('.png', '').toUpperCase(),
    key = `${g.set}-${g.border}-${material}`;
  const profile = {
    asset: g.source.asset.slice(sourceRoot.length),
    rect: g.source.rect,
    adjustment: g.adjustment,
  };
  if (frames[key]) assert.deepEqual(frames[key], profile, 'Ambiguous runtime group');
  frames[key] = profile;
}
for (const g of result.mana.filter((g) => g.status === 'trial')) {
  const cal = candidate.mana.find((c) => c.key === g.key);
  assert.equal(cal.status, 'trial');
  assert.deepEqual(cal.targetRgb, g.targetRgb);
  mana[`${g.set}-${g.border}-${g.symbol}`] = g.targetRgb;
}
await atomicWrite(
  `${root}/games/magic/src/presentation/old-hsb-profiles.ts`,
  `// Generated by old-hsb-adopt.mjs. Explicit opt-in; rejected groups stay unchanged.\n// Results SHA-256: ${hash(JSON.stringify(result))}\nimport type { HsbAdjustment, Rgb } from './hsb.js';\nimport type { FaceRect } from './face-layout.js';\nexport const OLD_HSB_FRAME_ROOT = ${JSON.stringify(sourceRoot)};\nexport const OLD_HSB_PROFILES: Readonly<Record<string,{asset:string;rect:FaceRect;adjustment:HsbAdjustment}>> = ${JSON.stringify(frames, null, 2)};\nexport const OLD_MANA_TARGETS: Readonly<Record<string,Rgb>> = ${JSON.stringify(mana, null, 2)};\n`,
);
await writeJson(`${fixtureRoot}/old-hsb-mana-review.json`, {
  schemaVersion: 1,
  resultsHash: hash(JSON.stringify(result)),
  sensitivityThreshold: 1.5,
  policy:
    'Diagnostic only; retain frozen coefficients and admission decisions. Median sensitivity was gated before reserved review; maxima expose individual outliers without retuning.',
  rows: result.mana
    .filter((g) => g.status === 'trial' && g.rows.some((r) => r.sensitivity > 1.5))
    .map((g) => ({
      key: g.key,
      status: 'admitted-with-outlier-review',
      maxReservedSensitivity: Math.max(...g.rows.map((r) => r.sensitivity)),
      sensitiveReferences: g.rows
        .filter((r) => r.sensitivity > 1.5)
        .map(({ id, sensitivity }) => ({ id, sensitivity })),
    })),
});
console.log(
  'Adopted',
  Object.keys(frames).length,
  'remaining-set whole-frame profiles and',
  Object.keys(mana).length,
  'mana targets.',
);
