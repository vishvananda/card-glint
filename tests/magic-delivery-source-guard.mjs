import { pre053Source } from './magic-053-source-guard.mjs';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { format } from 'prettier';
import { hash } from '../games/magic/tools/accuracy/common.mjs';
let verified;
export async function deliveryProof() {
  verified ??= (async () => {
    const p = JSON.parse(
      await readFile('games/magic/fixtures/accuracy/set-editor-delivery-compatibility.json'),
    );
    for (const [file, sha] of Object.entries(p.dependencies))
      assert.equal(
        hash(await pre053Source(file)),
        sha,
        'Unreviewed editor/data-delivery change: ' + file,
      );
    const bytes = await readFile('games/magic/fixtures/accuracy/set-editor-native-parity.json');
    assert.equal(hash(bytes), p.nativeHash);
    const native = JSON.parse(bytes);
    assert.equal(native.baselineCommit, p.baselineCommit);
    assert.equal(native.cards, 56);
    assert.equal(native.zeroCandidates, 44);
    assert.equal(new Set(native.rows.map((r) => r.id)).size, 56);
    for (const row of native.rows) {
      assert.equal(row.before, row.after, row.id);
      if (row.zero) assert.equal(row.zero, row.after, row.id);
    }
    const data = await readFile('games/magic/fixtures/accuracy/delivery-data-parity.json');
    assert.equal(hash(data), p.dataHash);
    assert.ok(JSON.parse(data).reviewGroups > 1800);
    const manifestPath = 'games/magic/src/data/generated-manifest.json';
    const generated = JSON.parse(await readFile(manifestPath));
    assert.equal(generated.schema, 1);
    for (const [file, sha] of Object.entries({ ...generated.sources, ...generated.files }))
      assert.equal(hash(await readFile(file)), sha, 'Stale generated data: ' + file);
    return { ...p, generatedModules: [...Object.keys(generated.files), manifestPath] };
  })();
  return verified;
}
/** Reconstruct the exact pre-editor source for historical assertions. Current
 * data is independently checked against authoritative profiles and evidence. */
export async function preDeliverySource(file) {
  const p = await deliveryProof(),
    bytes = await pre053Source(file),
    change = p.files[file];
  if (!change) return bytes;
  assert.equal(hash(bytes), change.after);
  let before;
  if (change.rebuild) {
    const evidence = JSON.parse(
      await readFile('games/magic/fixtures/accuracy/printing-review-catalog.json'),
    );
    const artist = change.rebuild === 'artist';
    const text = artist
      ? `// Generated by games/magic/tools/build-printing-corrections.mjs.\nimport type { ReviewedArtistCredit } from './artist.js';\nexport const artistCreditRevision = '${evidence.artistRevision}';\nexport const artistCredits: Readonly<Record<string, ReviewedArtistCredit>> = ${JSON.stringify(evidence.artists)};\n`
      : `// Generated by games/magic/tools/build-printing-corrections.mjs.\nimport type { ReviewedCorrection } from './types.js';\nexport const printingCorrectionRevision = '${evidence.revision}';\nexport const printingCorrections: Readonly<Record<string, readonly ReviewedCorrection[]>> = ${JSON.stringify(evidence.wording)};\n`;
    before = Buffer.from(
      await format(text, { parser: 'typescript', singleQuote: true, printWidth: 100 }),
    );
  } else {
    const lines = bytes.toString().match(/[^\n]*\n|[^\n]+$/g) || [];
    for (const edit of change.reverseEdits) lines.splice(edit.start, edit.count, ...edit.lines);
    before = Buffer.from(lines.join(''));
  }
  assert.equal(hash(before), change.before, 'Historical reconstruction ' + file);
  return before;
}
